export const t = (key: keyof typeof translations['vi'], lang: Language = 'vi', params?: Record<string, string | number>): string => {
  const dict = translations[lang] || translations.vi;
  let text = dict[key] || translations.vi[key] || key;
  if (params) {
    Object.keys(params).forEach(p => {
      text = text.replace(`{${p}}`, String(params[p]));
    });
  }
  return text;
};

export const formatRoomTitle = (roomName: string, lang: Language = 'vi'): string => {
  if (!roomName || roomName === 'Chưa xếp' || roomName === 'Unassigned' || roomName === 'Chưa xếp phòng') {
    return lang === 'en' ? 'Unassigned' : 'Chưa xếp phòng';
  }
  const cleanName = roomName.replace(/^(Phòng|Room)\s+/i, '').trim();
  return lang === 'en' ? `Room ${cleanName}` : `Phòng ${cleanName}`;
};

export const formatGenericValue = (value: string | undefined | null, lang: Language = 'vi'): string => {
  if (!value || value === 'Chưa cập nhật' || value === 'Not updated' || value === 'N/A') {
    return lang === 'en' ? 'Not updated' : 'Chưa cập nhật';
  }
  return value;
};

export const formatMonthPeriod = (monthStr: string, lang: Language = 'vi'): string => {
  if (!monthStr) return '';
  if (lang === 'en') {
    return monthStr.replace(/^Tháng\s+/i, 'Period ');
  }
  return monthStr;
};
